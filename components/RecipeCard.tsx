"use client";

import React, { useState } from "react";
import type { Recipe } from "@/types";
import { useChat } from "@/context/ChatContext";

interface RecipeCardProps {
  recipe: Recipe;
}

export function RecipeCard({ recipe }: RecipeCardProps) {
  const { t, saveRecipe, removeSavedRecipe, isRecipeSaved } = useChat();
  const [copied, setCopied] = useState(false);

  const isSaved = isRecipeSaved(recipe.title);

  const handleToggleSave = () => {
    if (isSaved) {
      removeSavedRecipe(recipe.title);
    } else {
      saveRecipe(recipe);
    }
  };

  const handleCopy = async () => {
    const text = `🍳 ${recipe.title}
⏱️ ${t.time}: ${recipe.time} | 👥 ${t.servings}: ${recipe.servings}

🛒 ${t.ingredients}:
${recipe.ingredients.map((i) => `• ${i.name} (${i.quantity})`).join("\n")}

👩‍🍳 ${t.instructions}:
${recipe.steps.map((s, i) => `${i + 1}. ${s}`).join("\n")}

Generated by ChefBot (https://cooking-chatbot-three.vercel.app)`;

    try {
      await navigator.clipboard.writeText(text);
      setCopied(true);
      setTimeout(() => setCopied(false), 2000);
    } catch (e) {
      console.error("Failed to copy", e);
    }
  };

  const handlePrint = () => {
    const printWindow = window.open("", "_blank");
    if (!printWindow) return;

    printWindow.document.write(`
      <html>
        <head>
          <title>${recipe.title} - ChefBot Recipe</title>
          <style>
            body { font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, sans-serif; padding: 30px; color: #222; }
            h1 { color: #d97706; border-bottom: 2px solid #fef3c7; padding-bottom: 8px; }
            .meta { font-size: 14px; color: #666; margin-bottom: 20px; }
            ul, ol { line-height: 1.6; }
            li { margin-bottom: 6px; }
          </style>
        </head>
        <body>
          <h1>🍳 ${recipe.title}</h1>
          <div class="meta">
            <strong>⏱️ ${t.time}:</strong> ${recipe.time} &nbsp;|&nbsp;
            <strong>👥 ${t.servings}:</strong> ${recipe.servings}
          </div>
          <h2>🛒 ${t.ingredients}</h2>
          <ul>
            ${recipe.ingredients
              .map((i) => `<li><strong>${i.name}:</strong> ${i.quantity}</li>`)
              .join("")}
          </ul>
          <h2>👩‍🍳 ${t.instructions}</h2>
          <ol>
            ${recipe.steps.map((s) => `<li>${s}</li>`).join("")}
          </ol>
        </body>
      </html>
    `);
    printWindow.document.close();
    printWindow.focus();
    printWindow.print();
  };

  return (
    <div className="recipe-card" id="recipe-card">
      {/* Header */}
      <div className="recipe-card-header">
        <h3 className="recipe-card-title">{recipe.title}</h3>
        
        {/* Quick Card Action Buttons */}
        <div className="recipe-card-actions">
          <button
            className={`btn-card-action ${isSaved ? "saved" : ""}`}
            onClick={handleToggleSave}
            title={isSaved ? t.saved : t.saveToCookbook}
          >
            {isSaved ? "⭐ " + t.saved : "🔖 " + t.saveToCookbook}
          </button>
          <button
            className="btn-card-action"
            onClick={handleCopy}
            title={t.copyRecipe}
          >
            {copied ? "✓ " + t.copied : "📋 " + t.copyRecipe}
          </button>
          <button
            className="btn-card-action btn-card-print"
            onClick={handlePrint}
            title={t.printRecipe}
          >
            🖨️
          </button>
        </div>
      </div>

      {/* Meta Badges */}
      <div className="recipe-card-meta">
        <span className="recipe-meta-badge">
          <span className="icon">⏱️</span>
          {recipe.time}
        </span>
        <span className="recipe-meta-badge">
          <span className="icon">🍽️</span>
          {recipe.servings} {t.servings}
        </span>
      </div>

      {/* Ingredients */}
      <div className="recipe-card-section">
        <h4 className="recipe-section-title">{t.ingredients}</h4>
        <div className="ingredients-grid">
          {recipe.ingredients.map((ing, i) => (
            <div key={i} className="ingredient-item">
              <span className="ingredient-bullet" />
              <span className="ingredient-quantity">{ing.quantity}</span>
              <span className="ingredient-name">{ing.name}</span>
            </div>
          ))}
        </div>
      </div>

      {/* Steps */}
      <div className="recipe-card-section">
        <h4 className="recipe-section-title">{t.instructions}</h4>
        <div className="steps-list">
          {recipe.steps.map((step, i) => (
            <div key={i} className="step-item">
              <span className="step-number">{i + 1}</span>
              <p className="step-text">{step}</p>
            </div>
          ))}
        </div>
      </div>
    </div>
  );
}
